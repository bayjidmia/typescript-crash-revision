// Type Inference is a feature in TypeScript that allows the compiler to automatically determine
//  the type of a variable based on its initial value. This means that you don't always have to
// explicitly specify the type of a variable, as TypeScript can infer it for you.
let message = "Hello, TypeScript!"; // Type is inferred as string
let age = 30; // Type is inferred as number
console.log(`Message: ${message}, Age: ${age}`);
